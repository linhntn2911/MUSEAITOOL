function canTransition(fromStatus, toStatus) {
  if (fromStatus === toStatus) return true;
  const allowed = ALLOWED_TRANSITIONS[fromStatus];
  if (!allowed) return false;
  return allowed.includes(toStatus);
}

function calculateProgress(status, evidence = []) {
  if (status === JOB_STATUSES.SCHEDULED || status === JOB_STATUSES.POSTED) {
    const hasEvidence = Array.isArray(evidence) && evidence.some(e =>
      e.type === "post_confirmed" || e.type === "schedule_confirmed"
    );
    return hasEvidence ? 100 : 95;
  }
  return PROGRESS_MAP[status] !== undefined ? PROGRESS_MAP[status] : 0;
}

function isSafePauseBoundary(status) {
  // Cannot pause safely while actively uploading or submitting
  return status !== JOB_STATUSES.UPLOADING && status !== JOB_STATUSES.SUBMITTING;
}

